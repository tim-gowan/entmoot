"""Authored C language controls; expectations are independent of parser output."""


def case(name, body, *, mode="c23", prefix="", sites=(), accepted=True, parse=True,
         execute=True, profile="stable", diagnostic=None, files=None):
    probe = "int probe(void) { " + body + " }"
    after = "int after(void) { return 7; }"
    source = prefix + "\n" + probe + "\n" + after + '\nint puts(const char *);\nint main(void) { if (probe() != 7) return 1; puts("oracle:ok"); return 0; }\n'
    return {"id": name, "language": "c", "mode": mode, "profile": profile,
            "source": source, "accepted": accepted, "parse": parse,
            "execute": execute and accepted, "diagnostic": diagnostic,
            "files": files or {},
            "after": after, "sites": [{"text": probe, "kind": "function_definition",
                                        "fields": {"declarator": "probe(void)"}}, *sites]}



//! Body-comment false positive for provisional heuristic structural skip.
//!
//! Fixture: `crates/entmoot-core/tests/fixtures/comment_calls/compiler_like.py`
#![allow(clippy::unwrap_used, clippy::expect_used)]

use entmoot_engine::{build_topology_from_repo_with_options, NodeKind, TopologyBuildOptions};
use std::path::PathBuf;

fn fixture_src() -> &'static str {
    include_str!("../../../crates/entmoot-core/tests/fixtures/comment_calls/compiler_like.py")
}

fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../crates/entmoot-core/tests/fixtures/comment_calls")
}

#[test]
fn body_comment_generated_by_still_inventories_callables() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("compiler_like.py"), fixture_src()).unwrap();

    let graph =
        build_topology_from_repo_with_options(dir.path(), TopologyBuildOptions::default()).unwrap();

    assert!(
        !graph
            .diagnostics
            .iter()
            .any(|d| d.code == "source.heuristic_skip"),
        "expected no heuristic_skip diagnostic; got {:?}",
        graph
            .diagnostics
            .iter()
            .map(|d| (&d.code, &d.message))
            .collect::<Vec<_>>()
    );

    let callable_names: Vec<_> = graph
        .nodes
        .iter()
        .filter(|n| n.kind == NodeKind::Callable)
        .map(|n| n.label.as_str())
        .collect();
    assert!(
        callable_names.len() == 2 && callable_names.iter().all(|name| *name == "as_sql"),
        "expected both as_sql overrides; callables={callable_names:?} fixture={}",
        fixture_dir().display()
    );
}

#[test]
fn nested_alias_override_path_preserves_each_callable_owner() {
    for (source, nested) in [
        (fixture_src().to_owned(), false),
        (fixture_src().to_owned(), true),
        (fixture_src().replace("generated by", "produced with"), true),
    ] {
        let dir = tempfile::tempdir().unwrap();
        let relative = if nested {
            "backend/mysql/compiler.py"
        } else {
            "compiler.py"
        };
        let file = dir.path().join(relative);
        std::fs::create_dir_all(file.parent().unwrap()).unwrap();
        std::fs::write(file, source).unwrap();
        let graph = build_topology_from_repo_with_options(dir.path(), Default::default()).unwrap();
        let mut owners: Vec<_> = graph
            .nodes
            .iter()
            .filter(|n| n.kind == NodeKind::Callable)
            .map(|n| {
                assert_eq!(n.path.as_deref(), Some(relative));
                n.fqn.as_deref().unwrap()
            })
            .collect();
        owners.sort();
        assert_eq!(owners.len(), 2, "{owners:?}");
        assert!(
            owners[0].ends_with("SQLDeleteCompiler.as_sql"),
            "{owners:?}"
        );
        assert!(
            owners[1].ends_with("SQLUpdateCompiler.as_sql"),
            "{owners:?}"
        );
    }
}

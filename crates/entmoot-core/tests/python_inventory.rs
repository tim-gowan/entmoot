//! Regression controls for Python alias imports and class overrides.

#[test]
fn relative_and_multiple_imports_retain_every_alias_and_target() {
    use entmoot_contracts::ImportKind;
    use entmoot_core::{resolve::resolve_file_calls, StructuralHasher};
    for (statement, expected) in [
        ("from .target import leaf as remote", vec![(".target.leaf", "remote")]),
        (
            "from ..target import leaf as remote, other as second",
            vec![("..target.leaf", "remote"), ("..target.other", "second")],
        ),
        (
            "from target import leaf, other as second",
            vec![("target.leaf", "leaf"), ("target.other", "second")],
        ),
        (
            "from .target import (leaf as remote,\n    # preserve the second import\n    café as second,\n)",
            vec![(".target.leaf", "remote"), (".target.café", "second")],
        ),
    ] {
        let calls = expected
            .iter()
            .map(|(_, local)| format!("    {local}()\n"))
            .collect::<String>();
        let source = format!("{statement}\ndef caller():\n{calls}");
        let hasher = StructuralHasher::new();
        let analyzed = hasher
            .compute_granular_hash_with_analysis(&source, "python", None)
            .unwrap();
        let plain = hasher.compute_granular_hash(&source, "python", None).unwrap();
        assert_eq!(analyzed.file_hash, plain.file_hash);
        let markers = analyzed.markers.as_ref().unwrap();
        assert_eq!(
            markers.imports.len(),
            expected.len(),
            "{statement}: {:?}",
            markers.imports
        );
        let calls = resolve_file_calls("package/client.py", &entmoot_core::build_file_index(&analyzed));
        for (target, local) in expected {
            let marker = markers
                .imports
                .iter()
                .find(|m| m.alias.as_deref() == Some(local))
                .unwrap();
            assert_eq!(marker.path, target);
            assert_eq!(marker.kind, ImportKind::Named);
            let call = calls.iter().find(|c| c.syntactic_callee == local).unwrap();
            assert_eq!(call.resolved_fqn.as_deref(), Some(target));
        }
    }
}

#[test]
fn duplicate_from_import_aliases_remain_ambiguous() {
    let source = "from .target import first as same, second as same\ndef caller():\n    same()\n";
    let result = entmoot_core::StructuralHasher::new()
        .compute_granular_hash_with_analysis(source, "python", None)
        .unwrap();
    let calls = entmoot_core::resolve::resolve_file_calls("client.py", &entmoot_core::build_file_index(&result));
    assert_eq!(calls.len(), 1);
    assert_eq!(calls[0].confidence, entmoot_core::resolve::ResolveConfidence::Ambiguous);
    assert_eq!(calls[0].resolved_fqn, None);
}

#[test]
fn python_alias_redefinition_preserves_definitions_and_callables() {
    let source = include_str!("../../../crates/entmoot-core/tests/fixtures/comment_calls/compiler_like.py");
    for source in [
        source.to_owned(),
        source.replace(
            "# Prefer the non-standard DELETE FROM syntax over the SQL generated by",
            "# ordinary body comment",
        ),
        source
            .replace(
                "from other.module import SQLDeleteCompiler as BaseSQLDeleteCompiler",
                "class BaseSQLDeleteCompiler: pass",
            )
            .replace(
                "from other.module import SQLUpdateCompiler as BaseSQLUpdateCompiler",
                "class BaseSQLUpdateCompiler: pass",
            ),
    ] {
        let result = entmoot_core::StructuralHasher::new()
            .compute_granular_hash_with_analysis(&source, "python", None)
            .expect("hash Python override fixture");
        let mut scopes: Vec<_> = result
            .markers
            .expect("analysis markers")
            .definitions
            .into_iter()
            .filter(|d| d.name == "as_sql")
            .map(|d| d.scope)
            .collect();
        scopes.sort();
        assert_eq!(scopes, vec![vec!["SQLDeleteCompiler"], vec!["SQLUpdateCompiler"]]);
        let mut names: Vec<_> = result.callables.values().map(|c| c.name.as_str()).collect();
        names.sort();
        assert_eq!(names, ["as_sql", "as_sql"]);
    }
}

"""Generate package-local derivation inputs. Run --check in CI; never edit outputs.

Cargo rewrites manifests when packaging. Normalize workspace inheritance here so
the checked-out and extracted packages commit to the same dependency policy.
The supported release build uses the committed lockfile (--locked).
"""
import argparse
import json
from pathlib import Path
import tomllib
import subprocess
import blake3

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("entmoot-contracts", "entmoot-core", "entmoot-topology")

HELPER = '''// Generated by scripts/prepare_release_inputs.py. Do not edit.
use std::{fs, io, path::Path};
fn collect(root: &Path, dir: &Path, files: &mut Vec<String>) -> io::Result<()> {
    println!("cargo:rerun-if-changed={}", dir.display());
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let kind = entry.file_type()?;
        if kind.is_symlink() { return Err(io::Error::other("derivation source symlink")); }
        if kind.is_dir() { collect(root, &entry.path(), files)?; }
        else if kind.is_file() {
            files.push(entry.path().strip_prefix(root).map_err(io::Error::other)?
                .to_string_lossy().replace('\\\\', "/"));
        }
    }
    Ok(())
}
pub fn emit() -> io::Result<()> {
    let root = std::env::var_os("CARGO_MANIFEST_DIR")
        .ok_or_else(|| io::Error::other("missing manifest directory"))?;
    let root = Path::new(&root);
    let mut files = vec!["build.rs".into(), "package_fingerprint.rs".into(), "derivation-inputs.json".into()];
    for extra in ["build_support.rs", "generated/grammars/manifest.rs"] {
        if root.join(extra).is_file() { files.push(extra.into()); }
    }
    collect(root, &root.join("src"), &mut files)?;
    files.sort();
    let mut hash = blake3::Hasher::new();
    hash.update(b"entmoot.package_derivation.v1\\0");
    for file in files {
        println!("cargo:rerun-if-changed={file}");
        let contents = fs::read_to_string(root.join(&file))?.replace("\\r\\n", "\\n");
        for field in [file.as_bytes(), contents.as_bytes()] {
            hash.update(&(field.len() as u64).to_le_bytes()); hash.update(field);
        }
    }
    println!("cargo:rustc-env=ENTMOOT_PACKAGE_FINGERPRINT={}", hash.finalize().to_hex());
    Ok(())
}
'''

def outputs():
    workspace = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))["workspace"]
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text(encoding="utf-8"))
    dependencies = [{k: p[k] for k in ("name", "version", "source", "checksum", "dependencies") if k in p}
                    for p in lock["package"] if "source" in p]
    for name in PACKAGES:
        directory = ROOT / "crates" / name
        manifest = tomllib.loads((directory / "Cargo.toml").read_text(encoding="utf-8"))
        for key, value in list(manifest["package"].items()):
            if isinstance(value, dict) and value.get("workspace"):
                manifest["package"][key] = workspace["package"][key]
        # Documentation/authors are not a derivation input. Dependencies and
        # features are, including build dependencies and target-specific tables.
        policy = {k: v for k, v in manifest.items() if k in
                  ("dependencies", "build-dependencies", "features", "target", "lib")}
        policy["package"] = {k: manifest["package"][k] for k in ("name", "version", "edition", "rust-version")}
        inputs = {"policy": policy, "lock": dependencies}
        if name == "entmoot-topology":
            # The v1 implementation fence remains conservative across the split.
            # These are generated digests, not compile/link dependencies. Shipping
            # packages carry this exact manifest so extracted builds agree.
            owners = ("entmoot-store", "entmoot-evidence", "entmoot-query", "entmoot-native", "entmoot-ops", "entmoot-workspace")
            sources = [path for owner in owners for path in (ROOT / "crates" / owner / "src").rglob("*") if path.is_file()]
            inputs["engine_derivations"] = {path.relative_to(ROOT).as_posix(): blake3.blake3(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest() for path in sorted(sources)}
            inputs["engine_policy"] = {owner: {key: value for key, value in tomllib.loads((ROOT / "crates" / owner / "Cargo.toml").read_text(encoding="utf-8")).items() if key in ("dependencies", "build-dependencies", "features", "target", "lib")} for owner in owners}
        yield directory / "derivation-inputs.json", json.dumps(inputs, sort_keys=True, indent=2) + "\n"
        yield directory / "package_fingerprint.rs", subprocess.run(["rustfmt", "--edition", "2021"], input=HELPER, text=True, capture_output=True, check=True, cwd=directory).stdout

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, expected in outputs():
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Regenerate release inputs: " + ", ".join(stale))

if __name__ == "__main__":
    main()
